/**
 * The claim tokens the web app's code writes (issue #354), found by reading
 * its sources.
 *
 * Procedure data, FAQ lists and landing pages name prices with tokens
 * (`[[price:tummy-tuck:full]]`) that the page resolves from the admin's
 * price list. The admin Pricing page refuses a save that would make a token
 * print nothing (a line deactivated, a starting line removed), but the
 * admin cannot read these files at runtime, so the list is generated into
 * `@workspace/shared/claims/code-tokens.generated` by
 * `pnpm --filter web claims:code-tokens`, and `code-tokens.test.ts` fails
 * while that file and the sources disagree.
 *
 * Only tokens that depend on the price list are collected: `price`,
 * `price-label`, `price-span` and `price-range`. Comments are skipped, as in
 * `no-typed-prices.test.ts`: they describe tokens, they don't print them.
 *
 * @module scripts/code-claim-tokens.lib
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/** `apps/web`. */
export const WEB_ROOT = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    '..'
)

/** The repository root, which the generated paths are relative to. */
export const REPO_ROOT = path.resolve(WEB_ROOT, '../..')

/** Where the generated constant lives. */
export const GENERATED_FILE = path.join(
    REPO_ROOT,
    'packages/shared/src/claims/code-tokens.generated.ts'
)

/** The source folders that print copy. */
const SOURCE_DIRS = ['app', 'components', 'lib']

/** A price-dependent claim token, as written. */
const PRICE_TOKEN =
    /\[\[price(?:-label|-span|-range)?(?::[a-z0-9][a-z0-9-]*)+\]\]/g

/** `findLinePrice(prices, 'mini')`, `getLinePrice('lipo', 'lipo360')`. */
const FIXED_LINE_LOOKUP =
    /\b(?:findLinePrice|getLinePrice)\(\s*[^,()]+,\s*['"]([a-z0-9-]+)['"]\s*\)/g

export interface CodeClaimToken {
    token: string
    files: string[]
}

function sourceFiles(dir: string): string[] {
    return readdirSync(dir).flatMap((name) => {
        const full = path.join(dir, name)
        if (statSync(full).isDirectory()) return sourceFiles(full)
        return /\.tsx?$/.test(name) && !/\.d\.ts$/.test(name) ? [full] : []
    })
}

/** The file without its comments. */
export function stripComments(source: string): string {
    return source
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .replace(/^\s*\/\/.*$/gm, '')
        .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
}

function webSources(): { file: string; code: string }[] {
    return SOURCE_DIRS.flatMap((dir) =>
        sourceFiles(path.join(WEB_ROOT, dir))
    ).map((file) => ({
        file: path.relative(REPO_ROOT, file).split(path.sep).join('/'),
        code: stripComments(readFileSync(file, 'utf8')),
    }))
}

/**
 * Every price token the web code writes, sorted, with the files (sorted)
 * that write it.
 */
export function scanCodeClaimTokens(): CodeClaimToken[] {
    const byToken = new Map<string, Set<string>>()
    for (const { file, code } of webSources()) {
        for (const match of code.matchAll(PRICE_TOKEN)) {
            const files = byToken.get(match[0]) ?? new Set<string>()
            files.add(file)
            byToken.set(match[0], files)
        }
    }
    return [...byToken.entries()]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([token, files]) => ({ token, files: [...files].sort() }))
}

/** Every line a component looks up by a fixed key, and where. */
export function scanFixedLineLookups(): { file: string; key: string }[] {
    return webSources().flatMap(({ file, code }) =>
        [...code.matchAll(FIXED_LINE_LOOKUP)].map((match) => ({
            file,
            key: match[1] ?? '',
        }))
    )
}

/** The generated module, before Prettier. */
export function renderCodeClaimTokensModule(tokens: CodeClaimToken[]): string {
    return `/**
 * GENERATED by apps/web/scripts/generate-code-claim-tokens.ts. Do not edit.
 *
 * Every price claim token the web app's code writes (procedure data, FAQ
 * lists, landing pages), with the files that write it. Regenerate with
 * \`pnpm --filter web claims:code-tokens\` after adding or removing one;
 * \`apps/web/__tests__/lib/claims/code-tokens.test.ts\` fails until you do.
 * See \`./code-tokens.ts\`.
 */
export const CODE_DATA_TOKENS: readonly {
    readonly token: string
    readonly files: readonly string[]
}[] = ${JSON.stringify(tokens, null, 4)}
`
}
