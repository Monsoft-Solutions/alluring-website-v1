/**
 * Generates src/claims/patterns.data.json from section 11 of the claims canon
 * (docs/claims/canon.md, issue #354).
 *
 * Usage (from packages/shared):
 *   node scripts/generate-claim-patterns.mjs
 *
 * The canon is the source: its code blocks hold the neutralizers and the
 * `ID  pattern` lines, and each rule's bullet ("- **CR1 (fail):** …") gives
 * its severity label and note. The JSON is checked in, because the Python
 * blog tools (blog/tools/lib/bloglib.py) read it without a JS build, and
 * `apps/admin/__tests__/lib/claims/patterns.test.ts` fails when the JSON and
 * the canon disagree. Edit the canon, then run this.
 *
 * Severity is read from the bullet label:
 *   fail    a hit is a defect ("fail", "fail until D9", "fail, 456.062")
 *   paired  a hit is a defect unless the paired check in the note passes
 *           ("fail unless …", "paired check", "allowed-set check", "fail, except")
 *   review  a person or the Opus pass reads the hit ("review", "follows D7")
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const CANON = join(here, '../../../docs/claims/canon.md')
const OUT = join(here, '../src/claims/patterns.data.json')

const GROUPS = {
    CR: 'credentials',
    FA: 'facility',
    EX: 'experience',
    PR: 'prices',
    SU: 'superlatives',
    TR: 'travel',
    MD: 'medical',
    CO: 'contact',
}

/** Rules the canon runs on one kind of field only. */
const SCOPES = { CR13: 'title', EX5: 'source' }

/**
 * CR9 is one pattern with two verdicts: Dr. Lofman fails, Dr. Shats is
 * flagged only until D1 is decided. The pattern stays verbatim; a hit that
 * also matches `downgrade.pattern` takes the lower severity.
 */
const DOWNGRADES = {
    CR9: {
        pattern: '\\bshats\\b',
        severity: 'review',
        reason: 'D1: flag Dr. Rita Shats, do not delete her mentions.',
    },
}

function severityOf(label) {
    if (/fail unless|paired check|allowed-set check|fail, except/.test(label))
        return 'paired'
    if (/^review$|^follows d7$/i.test(label)) return 'review'
    if (/^fail/.test(label)) return 'fail'
    throw new Error(`Unknown severity label: "${label}"`)
}

const canon = readFileSync(CANON, 'utf8')
const start = canon.indexOf('## 11. Forbidden-claim regex list')
const end = canon.indexOf('## 12.')
if (start === -1 || end === -1) throw new Error('Section 11 not found')
const section = canon.slice(start, end)

const blocks = [...section.matchAll(/```\n([\s\S]*?)\n```/g)].map((m) => m[1])
const [neutralBlock, ...ruleBlocks] = blocks
const neutralizers = neutralBlock.split('\n').filter(Boolean)

/** id -> { label, note } from the bullets; "PR1 and PR2" share one. */
const bullets = new Map()
for (const m of section.matchAll(
    /^- \*\*([A-Z]{2}\d+)(?: and ([A-Z]{2}\d+))? \(([^)]*)\)(?::\*\* ?(.*)|\.\*\*)$/gm
)) {
    const [, first, second, label, note = ''] = m
    for (const id of [first, second].filter(Boolean))
        bullets.set(id, { label, note: note.trim() })
}

const rules = []
for (const block of ruleBlocks) {
    for (const line of block.split('\n')) {
        const m = /^([A-Z]{2}\d+)\s+(.*)$/.exec(line)
        if (!m) throw new Error(`Unparsed rule line: ${line}`)
        const [, id, pattern] = m
        const bullet = bullets.get(id)
        if (!bullet) throw new Error(`No bullet for ${id}`)
        const label = bullet.label
        const rule = {
            id,
            group: GROUPS[id.slice(0, 2)],
            pattern,
            severity: id === 'CR9' ? 'fail' : severityOf(label.toLowerCase()),
            label,
            note: bullet.note,
            scope: SCOPES[id] ?? 'text',
        }
        if (DOWNGRADES[id]) rule.downgrade = DOWNGRADES[id]
        rules.push(rule)
    }
}

const data = {
    $comment:
        'Generated by packages/shared/scripts/generate-claim-patterns.mjs from docs/claims/canon.md section 11. Do not edit by hand.',
    source: 'docs/claims/canon.md#11-forbidden-claim-regex-list',
    flags: 'i',
    neutralizers,
    rules,
}

writeFileSync(OUT, `${JSON.stringify(data, null, 4)}\n`)
console.log(
    `Wrote ${rules.length} rules and ${neutralizers.length} neutralizers to ${OUT}`
)
